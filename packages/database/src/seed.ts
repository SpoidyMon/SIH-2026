async function main() {
  console.log('🌱 Starting database seeding for official commodities & Pune/PCMC mandis...');

  // 1. Seed Official 51 Commodities
  console.log(`📦 Seeding ${OFFICIAL_COMMODITIES.length} official commodities...`);
  for (const item of OFFICIAL_COMMODITIES) {
    await prisma.commodity.upsert({
      where: { name: item.name },
      update: { category: item.category },
      create: {
        name: item.name,
        category: item.category,
        defaultUnit: 'kg',
      },
    });
  }

  // 2. Seed Mandis
  console.log(`🏛️  Seeding ${PIMPRI_PUNE_MANDIS.length} real APMC mandis...`);
  for (const mandi of PIMPRI_PUNE_MANDIS) {
    const operatorEmail = `${mandi.apmcCode.toLowerCase().replace(/-/g, '_')}@farmersetu.in`;

    // 2.1 Upsert Operator User
    const operatorUser = await prisma.user.upsert({
      where: { email: operatorEmail },
      update: {
        name: `${mandi.name.split(' ')[0]} Operator`,
        role: Role.MANDI_OPERATOR,
        isVerified: true,
      },
      create: {
        email: operatorEmail,
        name: `${mandi.name.split(' ')[0]} Operator`,
        passwordHash: '$2b$10$epG/2q1/d51v.1iG.hH2.e1vL3p24r.15iT41235123451234512',
        role: Role.MANDI_OPERATOR,
        isVerified: true,
      },
    });

    // 2.2 Upsert MandiProfile
    const mandiProfile = await prisma.mandiProfile.upsert({
      where: { userId: operatorUser.id },
      update: {
        mandiName: mandi.name,
        apmcCode: mandi.apmcCode,
        address: mandi.address,
        district: mandi.district,
        state: mandi.state,
        latitude: mandi.latitude,
        longitude: mandi.longitude,
        topCrop: mandi.topCrop,
        acceptedCrops: mandi.acceptedCrops,
        modalPrice: mandi.modalPrice,
        priceTrend: mandi.priceTrend,
        trendDirection: mandi.trendDirection,
        estimatedQueueTime: mandi.estimatedQueueTime,
        activeFarmersCount: mandi.activeFarmersCount,
        operatingHours: mandi.operatingHours,
        approvalStatus: MandiApprovalStatus.APPROVED,
        approvedAt: new Date(),
        isOpen: true,
      },
      create: {
        userId: operatorUser.id,
        mandiName: mandi.name,
        apmcCode: mandi.apmcCode,
        address: mandi.address,
        district: mandi.district,
        state: mandi.state,
        latitude: mandi.latitude,
        longitude: mandi.longitude,
        topCrop: mandi.topCrop,
        acceptedCrops: mandi.acceptedCrops,
        modalPrice: mandi.modalPrice,
        priceTrend: mandi.priceTrend,
        trendDirection: mandi.trendDirection,
        estimatedQueueTime: mandi.estimatedQueueTime,
        activeFarmersCount: mandi.activeFarmersCount,
        operatingHours: mandi.operatingHours,
        approvalStatus: MandiApprovalStatus.APPROVED,
        approvedAt: new Date(),
        isOpen: true,
      },
    });

    // 2.3 Upsert Active Mandi Auction Slots for today and upcoming days
    const todayStr: string = new Date().toISOString().split('T')[0] || '2026-09-09';
    const tomorrowStr: string = new Date(Date.now() + 86400000).toISOString().split('T')[0] || '2026-09-10';

    const slotData = [
      {
        crop: mandi.acceptedCrops[0] || 'Onion',
        date: todayStr,
        startTime: '07:00',
        endTime: '11:00',
        totalCapacityQuintals: 500,
        maxFarmers: 40,
        availableBookings: 28,
        bookedFarmers: 12,
      },
      {
        crop: mandi.acceptedCrops[1] || mandi.acceptedCrops[0] || 'Tomato',
        date: todayStr,
        startTime: '11:30',
        endTime: '15:30',
        totalCapacityQuintals: 450,
        maxFarmers: 35,
        availableBookings: 25,
        bookedFarmers: 10,
      },
      {
        crop: mandi.acceptedCrops[0] || 'Wheat',
        date: tomorrowStr,
        startTime: '07:00',
        endTime: '11:00',
        totalCapacityQuintals: 600,
        maxFarmers: 50,
        availableBookings: 45,
        bookedFarmers: 5,
      },
    ];

    for (const slot of slotData) {
      const existingSlot = await prisma.mandiSlot.findFirst({
        where: {
          mandiProfileId: mandiProfile.id,
          date: slot.date,
          startTime: slot.startTime,
        },
      });

      if (!existingSlot) {
        await prisma.mandiSlot.create({
          data: {
            mandiProfileId: mandiProfile.id,
            crop: slot.crop,
            date: slot.date || todayStr,
            startTime: slot.startTime,
            endTime: slot.endTime,
            totalCapacityQuintals: slot.totalCapacityQuintals,
            maxFarmers: slot.maxFarmers,
            availableBookings: slot.availableBookings,
            bookedFarmers: slot.bookedFarmers,
            isActive: true,
          },
        });
      }
    }
  }

  console.log(`✅ Successfully seeded 51 official commodities and ${PIMPRI_PUNE_MANDIS.length} mandis with multi-crop support!`);
}

main()
  .catch((e) => {
    console.error('❌ Error during seeding:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
