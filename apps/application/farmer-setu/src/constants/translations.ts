/**
 * Automatically localize mandi names based on active language
 */
export function translateMandiName(name: string, lang: SupportedLanguage): string {
  if (lang === 'en') return name;
  return MANDI_NAME_TRANSLATIONS[lang]?.[name] || name;
}

/**
 * Automatically localize crop names based on active language
 */
export function translateCropName(crop: string, lang: SupportedLanguage): string {
  if (lang === 'en') return crop;
  return CROP_NAME_TRANSLATIONS[lang]?.[crop] || crop;
}

